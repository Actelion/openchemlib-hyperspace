package com.idorsia.research.chem.hyperspace.workbench;

import com.actelion.research.chem.*;
import com.idorsia.research.chem.hyperspace.rawspace.*;
import java.io.*;
import java.nio.file.*;
import java.util.*;
import java.util.zip.GZIPOutputStream;

/** Redistributable synthetic example, generated from these public literal structures, never supplier data. */
public final class ToySetup {
    private ToySetup(){}
    public static RawSynthonSpace raw()throws Exception {
        var builder=RawSynthonSpace.builder("Workbench synthetic alkyl coupling")
                .putMetadata("source.format","workbench-public-toy-v1");
        for(String reaction:List.of("alkyl-A","alkyl-B")) {
            builder.addRawFragments(reaction,0,List.of(synthon(reaction,0,"a","[U]CCC"),synthon(reaction,0,"b","[U]CCN")));
            builder.addRawFragments(reaction,1,List.of(synthon(reaction,1,"x","[U]CCO"),synthon(reaction,1,"y","[U]CCC")));
            builder.addReactionMetadata(reaction,"source.provenance","Synthetic minimal example; freely redistributable.");
        }
        return builder.build();
    }
    private static RawSynthon synthon(String reaction,int position,String id,String smiles)throws Exception {
        var molecule=new StereoMolecule();new SmilesParser().parse(molecule,smiles);return RawSynthon.fromMolecule(reaction,position,reaction+"-"+id,molecule);
    }
    public static Map<String,String> prepare(Path directory,int threads)throws Exception {
        Files.createDirectories(directory);var raw=raw();Path rawPath=directory.resolve("toy.rawspace.gz");RawSynthonSpaceIO.write(raw,rawPath);
        var space=RawSynthonSpaceAssembler.buildSynthonSpace(raw,RawSynthonSpaceAssembler.BuildOptions.builder().descriptorShortName("FragFp").descriptorBits(512).threads(threads).validateReactions(true).build());
        Path index=directory.resolve("toy.data");try(var out=new ObjectOutputStream(new GZIPOutputStream(Files.newOutputStream(index)))){out.writeObject(space);}
        Files.writeString(directory.resolve("molecules.tsv"),"id\tsmiles\nethanol\tCCO\nhexanol\tCCCCCCO\nhexane\tCCCCCC\nphenol\tOc1ccccc1\ncyclohexane\tC1CCCCC1\ncaffeine\tCn1c(=O)c2c(ncn2C)n(C)c1=O\n");
        Files.writeString(directory.resolve("PROVENANCE.txt"),"Format version 1. Freely redistributable synthetic toy generated by Hyperspace ToySetup. Two reactions with 2x2 synthons each (8 source tuples); molecular identities overlap intentionally across reactions. No supplier structures.\n");
        return Map.of("rawspace",rawPath.toAbsolutePath().toString(),"substructureIndex",index.toAbsolutePath().toString(),"moleculeTable",directory.resolve("molecules.tsv").toAbsolutePath().toString());
    }
    public static void main(String[] args)throws Exception {
        if(args.length!=1)throw new IllegalArgumentException("Usage: ToySetup OUTPUT_DIRECTORY");
        System.out.println(WorkspaceStore.JSON.writeValueAsString(prepare(Path.of(args[0]),1)));
    }
}
